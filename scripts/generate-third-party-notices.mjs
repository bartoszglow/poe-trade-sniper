#!/usr/bin/env node
/**
 * Regenerates THIRD-PARTY-NOTICES.md from the production dependency tree.
 *
 * This file is a LEGAL OBLIGATION, not documentation: MIT, ISC, BSD and
 * Apache-2.0 all require that their copyright + permission notice travel with
 * every binary we ship. LICENSE §7 points users here.
 *
 * Run it whenever production dependencies change:
 *   node scripts/generate-third-party-notices.mjs
 *
 * It shells out to `pnpm licenses list --prod --json`, then reads each package's
 * own LICENSE file from the store so the notice carries the real copyright
 * lines, not a guess from the SPDX id.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUTPUT = 'THIRD-PARTY-NOTICES.md';
const LICENSE_FILE = /^(licen[sc]e|copying)(\.md|\.txt)?$/i;

/** The bundled runtime isn't an npm dep of ours, but we ship it. */
const EXTRA_NOTES = [
  {
    name: 'Electron (bundled runtime)',
    note: "The packaged app embeds Electron, which itself bundles Chromium and Node.js. Electron is MIT-licensed; Chromium and Node.js carry their own notices, viewable in the app under Electron's built-in `chrome://credits` equivalent and in the Electron distribution.",
  },
];

function readLicenseText(path) {
  if (!path || !existsSync(path)) return null;
  const entry = readdirSync(path).find((file) => LICENSE_FILE.test(file));
  if (!entry) return null;
  const text = readFileSync(join(path, entry), 'utf8').trim();
  return text.length > 0 ? text : null;
}

const raw = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], {
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});

/** { [spdx]: Array<{name, versions, paths, homepage, license}> } */
const byLicense = JSON.parse(raw);

const packages = [];
for (const [license, entries] of Object.entries(byLicense)) {
  for (const entry of entries) {
    packages.push({
      name: entry.name,
      license,
      versions: (entry.versions ?? []).join(', '),
      homepage: entry.homepage ?? null,
      text: readLicenseText((entry.paths ?? [])[0]),
    });
  }
}
packages.sort((a, b) => a.name.localeCompare(b.name));

const licenseCounts = Object.entries(byLicense)
  .map(([license, entries]) => [license, entries.length])
  .sort((a, b) => b[1] - a[1]);

const lines = [];
lines.push('# Third-party notices');
lines.push('');
lines.push('PoE Trade Sniper is proprietary (see `LICENSE`), but it is built on');
lines.push('open-source components. Each component below is licensed by its own authors');
lines.push('under its own terms, reproduced here as those licences require. Those terms');
lines.push('govern those components; nothing in our `LICENSE` restricts the rights they');
lines.push('grant you.');
lines.push('');
lines.push('> Generated by `scripts/generate-third-party-notices.mjs` — do not edit by hand.');
lines.push(`> ${packages.length} production packages.`);
lines.push('');
lines.push('## Summary');
lines.push('');
lines.push('| Licence | Packages |');
lines.push('| ------- | -------- |');
for (const [license, count] of licenseCounts) lines.push(`| ${license} | ${count} |`);
lines.push('');
for (const extra of EXTRA_NOTES) {
  lines.push(`**${extra.name}** — ${extra.note}`);
  lines.push('');
}
lines.push('## Packages');
lines.push('');

for (const pkg of packages) {
  lines.push(`### ${pkg.name}${pkg.versions ? ` (${pkg.versions})` : ''}`);
  lines.push('');
  lines.push(`Licence: ${pkg.license}`);
  if (pkg.homepage) lines.push(`Homepage: ${pkg.homepage}`);
  lines.push('');
  if (pkg.text) {
    lines.push('```text');
    lines.push(pkg.text);
    lines.push('```');
  } else {
    lines.push(
      `_No licence file shipped in this package; it declares **${pkg.license}**. See its homepage for the canonical text._`,
    );
  }
  lines.push('');
}

writeFileSync(OUTPUT, `${lines.join('\n')}\n`);
console.warn(`${OUTPUT}: ${packages.length} packages, ${licenseCounts.length} distinct licences`);
